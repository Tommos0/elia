defmodule EliaWeb.Endpoint do
  use Phoenix.Endpoint, otp_app: :elia

  # The session will be stored in the cookie and signed,
  # this means its contents can be read but not tampered with.
  # Set :encryption_salt if you would also like to encrypt it.
  @session_options [
    store: :cookie,
    key: "_elia_key",
    signing_salt: "FEc/xgkc",
    same_site: "Lax"
  ]

  # Sockets never reload code on connect: a deploy loads code, never a request
  # (see Elia.Deploy).
  # peer_data and user_agent feed the sessions page (EliaWeb.ClientTracker);
  # x_headers exposes X-Forwarded-For from reverse proxies like Cloudflare.
  @connect_info [:peer_data, :x_headers, :user_agent, session: @session_options]

  socket "/live", Phoenix.LiveView.Socket,
    websocket: [connect_info: @connect_info, code_reloader: false],
    longpoll: [connect_info: @connect_info, code_reloader: false]

  # TERM-12: a chat's terminal streams over a channel of its own — a terminal is
  # bytes, not markup, so it does not go through a LiveView's diffing. Same
  # connect_info as the LiveView socket, and the same rule: a socket connect
  # never reloads code.
  socket "/terminal", EliaWeb.TerminalSocket,
    websocket: [connect_info: @connect_info, code_reloader: false],
    longpoll: [connect_info: @connect_info, code_reloader: false]

  # Serve at "/" the static files from "priv/static" directory.
  #
  # When code reloading is disabled (e.g., in production),
  # the `gzip` option is enabled to serve compressed
  # static files generated by running `phx.digest`.
  plug Plug.Static,
    at: "/",
    from: :elia,
    gzip: not code_reloading?,
    only: EliaWeb.static_paths(),
    raise_on_missing_only: code_reloading?

  # Code reloading can be explicitly enabled under the
  # :code_reloader configuration of your endpoint.
  if code_reloading? do
    socket "/phoenix/live_reload/socket", Phoenix.LiveReloader.Socket,
      websocket: [code_reloader: false]

    plug Phoenix.LiveReloader
    # Never reloads on a request; only a deploy loads code (DEPLOY-8).
    plug Phoenix.CodeReloader, reloader: &Elia.Deploy.reload/2
  end

  plug Plug.RequestId
  plug Plug.Telemetry, event_prefix: [:phoenix, :endpoint]

  plug Plug.Parsers,
    parsers: [:urlencoded, :multipart, :json],
    pass: ["*/*"],
    json_decoder: Phoenix.json_library()

  plug Plug.MethodOverride
  plug Plug.Head
  plug Plug.Session, @session_options
  plug EliaWeb.Router
end
